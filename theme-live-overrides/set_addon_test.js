const { chromium } = require('playwright');
const T = '156956393633', base = 'https://elsewhereapparelco.com';
const OUT = __dirname + '/';
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 } })).newPage();
  const errs = [];
  p.on('pageerror', (e) => { if (!/tiktok|Failed to fetch/.test(e.message)) errs.push(e.message); });
  await p.goto(`${base}/products/final-boss-energy-hoodie?preview_theme_id=${T}`, { waitUntil: 'domcontentloaded', timeout: 90000 });
  await p.waitForTimeout(1500);
  const emptyCart = () => p.evaluate(() => fetch('/cart/update.js', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ updates: {} }) }).then(() => fetch('/cart.js')).then((r) => r.json()).then((c) => Promise.all(c.items.map((i) => fetch('/cart/change.js', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: i.key, quantity: 0 }) })))));
  await emptyCart();
  console.log('ask:', await p.textContent('.mw-set__title'));
  console.log('panel hidden before:', await p.$eval('[data-set-panel]', (e) => e.hidden));
  await p.click('.mw-set__ask');
  await p.waitForTimeout(300);
  console.log('panel hidden after:', await p.$eval('[data-set-panel]', (e) => e.hidden), '| button:', (await p.textContent('[data-add-button]')).trim());
  await p.click('fieldset.option label:text-is("L")').catch(() => {});
  await p.waitForTimeout(300);
  await p.click('[data-set-colors] label:text-is("Navy")');
  await p.waitForTimeout(300);
  console.log('pants picks:', await p.$eval('[data-set-addon]', (x) => [...x.querySelectorAll('input[type=radio]:checked')].map((i) => i.value).join(',')));
  console.log('summary:', (await p.textContent('.mw-set__sum')).replace(/\s+/g, ' ').trim(), '|', await p.textContent('[data-set-note]'));
  await p.$eval('[data-set-addon]', (e) => e.scrollIntoView({ block: 'center' }));
  await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + 'addon.png' });
  console.log('before add:', await p.evaluate(() => { const b = document.querySelector('[data-set-addon]'); const f = document.getElementById(b.dataset.for); return { for: b.dataset.for, formFound: !!f, formId: f && f.id, pants: b.dataset.pantsVariant, yes: b.querySelector('[data-set-yes]').checked }; }));
  p.on('request', (r) => { if (r.url().includes('cart/add')) console.log('REQUEST', r.method(), r.url(), (r.postData() || '').slice(0, 200)); });
  p.on('response', async (r) => { if (r.url().includes('cart/add')) console.log('RESPONSE', r.status(), (await r.text()).slice(0, 200)); });
  await p.click('[data-add-button]');
  await p.waitForTimeout(3500);
  const cart = await p.evaluate(async () => (await (await fetch('/cart.js')).json()));
  console.log('cart:', cart.items.map((i) => `${i.product_title} [${i.variant_title}] x${i.quantity} $${(i.final_line_price / 100).toFixed(2)}`).join(' | '), '| total $' + (cart.total_price / 100).toFixed(2));
  await p.screenshot({ path: OUT + 'addon_cart.png' });
  await emptyCart();
  console.log('errors', errs.length ? errs : 'none');
  await b.close();
})();
